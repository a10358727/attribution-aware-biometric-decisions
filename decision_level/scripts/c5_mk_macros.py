def f(x, d=3):
    s = f"{x:.{d}f}"
    return s.replace("-", "\\ensuremath{-}")


def pp(x, d=0):                    # proportion -> percent string
    return f"{100 * x:.{d}f}"


M = {}


def tr(name):
    for a, b in list(EST.items()) + list(EPN.items()):
        name = name.replace(a, b)
    return name


